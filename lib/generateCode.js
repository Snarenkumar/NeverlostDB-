/**
 * generateCode.js
 *
 * Pure function that takes form state from the Configure page
 * and returns generated code strings (install command, .env example, setup.js).
 *
 * This file has ZERO side effects — it only produces strings.
 */

/**
 * Maps the backup interval selection to a cron expression or ms value
 */
function getIntervalValue(interval, custom) {
  const map = {
    '30m': '30m',
    '1h': '1h',
    '2h': '2h',
    '6h': '6h',
    '12h': '12h',
    '24h': '24h',
  };
  if (interval === 'custom') {
    return custom || '1h';
  }
  return map[interval] || '1h';
}

/**
 * Generate the install command string
 */
export function generateInstallCmd() {
  return 'npm install db-guardian';
}

/**
 * Generate the .env.example content
 */
export function generateEnvExample(formData) {
  const lines = [
    '# ===========================================',
    '# DB Guardian — Environment Variables',
    '# ===========================================',
    '# IMPORTANT: Never commit this file to GitHub!',
    '# Add .env to your .gitignore file.',
    '',
  ];

  formData.databases.forEach((db, i) => {
    const num = i + 1;
    const typeLabel = db.type === 'mongodb' ? 'MongoDB' : 'Supabase/PostgreSQL';
    lines.push(`# Database ${num} (${typeLabel}) — Role: ${db.role}`);
    lines.push(`DB${num}_URL=${db.url || `your_database_${num}_connection_url_here`}`);
    lines.push('');
  });

  if (formData.keepAlive.backendAwake && formData.keepAlive.backendUrl) {
    lines.push('# Backend URL for keep-alive pinging');
    lines.push(`BACKEND_URL=${formData.keepAlive.backendUrl}`);
    lines.push('');
  }

  if (formData.alerts.enabled && formData.alerts.webhook) {
    const methodLabel = formData.alerts.method.charAt(0).toUpperCase() + formData.alerts.method.slice(1);
    lines.push(`# ${methodLabel} alert webhook/endpoint`);
    lines.push(`ALERT_WEBHOOK=${formData.alerts.webhook}`);
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Generate the main setup.js code
 */
export function generateSetupCode(formData) {
  const lines = [];

  // Header comment
  lines.push('// ===========================================');
  lines.push('// DB Guardian — Auto-generated Setup');
  lines.push('// ===========================================');
  lines.push('// This file was generated by https://db-guardian.dev');
  lines.push('// Paste this into your project and run it to start');
  lines.push('// protecting your databases.');
  lines.push('// ===========================================');
  lines.push('');

  // Imports
  lines.push("const { DBGuardian } = require('db-guardian');");
  lines.push("require('dotenv').config();");
  lines.push('');

  // Database connections array
  lines.push('// ---- Database Connections ----');
  lines.push('// Define all your database connections here.');
  lines.push('// The URLs are read from your .env file for security.');
  lines.push('const databases = [');

  formData.databases.forEach((db, i) => {
    const num = i + 1;
    const comma = i < formData.databases.length - 1 ? ',' : '';
    lines.push('  {');
    lines.push(`    name: "db${num}",`);
    lines.push(`    type: "${db.type}",`);
    lines.push(`    url: process.env.DB${num}_URL,`);
    lines.push(`    role: "${db.role}",`);
    lines.push(`  }${comma}`);
  });

  lines.push('];');
  lines.push('');

  // Backup config
  lines.push('// ---- Backup Settings ----');
  lines.push('// Controls how often and how your data gets backed up.');
  const intervalVal = getIntervalValue(formData.backup.interval, formData.backup.custom);

  lines.push('const backupConfig = {');
  lines.push(`  interval: "${intervalVal}",`);
  lines.push(`  mode: "${formData.backup.mode}",  // "${formData.backup.mode === 'mirror' ? 'mirror: completely overwrite the backup target' : 'merge: only add new or changed records'}"`);

  if (formData.backup.specificCollections && formData.backup.collections) {
    const cols = formData.backup.collections.split(',').map(c => `"${c.trim()}"`).join(', ');
    lines.push(`  collections: [${cols}],  // Only back up these specific collections/tables`);
  }

  lines.push('};');
  lines.push('');

  // Keep-alive config
  if (formData.keepAlive.backendAwake || formData.keepAlive.dbAwake) {
    lines.push('// ---- Keep-Alive Settings ----');
    lines.push('// Prevents free-tier services from sleeping due to inactivity.');
    lines.push('const keepAliveConfig = {');

    if (formData.keepAlive.backendAwake) {
      lines.push('  backend: {');
      lines.push('    enabled: true,');
      lines.push('    url: process.env.BACKEND_URL,');
      lines.push(`    interval: "${formData.keepAlive.pingInterval}",  // Ping every ${formData.keepAlive.pingInterval}`);
      lines.push('  },');
    }

    if (formData.keepAlive.dbAwake) {
      lines.push('  databases: {');
      lines.push('    enabled: true,  // Will ping all connected databases to keep them awake');
      lines.push('  },');
    }

    lines.push('};');
    lines.push('');
  }

  // Alerts config
  if (formData.alerts.enabled) {
    lines.push('// ---- Alert Settings ----');
    lines.push('// Get notified immediately when something goes wrong.');
    lines.push('const alertConfig = {');
    lines.push('  enabled: true,');
    lines.push(`  method: "${formData.alerts.method}",`);

    if (formData.alerts.method === 'email') {
      lines.push('  email: process.env.ALERT_WEBHOOK,');
    } else {
      lines.push('  webhookUrl: process.env.ALERT_WEBHOOK,');
    }

    lines.push('};');
    lines.push('');
  }

  // Initialize DB Guardian
  lines.push('// ---- Initialize DB Guardian ----');
  lines.push('// This brings everything together and starts the protection.');
  lines.push('const guardian = new DBGuardian({');
  lines.push('  databases,');
  lines.push('  backup: backupConfig,');

  if (formData.keepAlive.backendAwake || formData.keepAlive.dbAwake) {
    lines.push('  keepAlive: keepAliveConfig,');
  }

  if (formData.alerts.enabled) {
    lines.push('  alerts: alertConfig,');
  }

  lines.push('});');
  lines.push('');

  // Start
  lines.push('// ---- Start Protection ----');
  lines.push('// Call .start() to begin automatic backups, keep-alive pings,');
  lines.push('// and failover monitoring.');
  lines.push('guardian.start()');
  lines.push('  .then(() => {');
  lines.push("    console.log('DB Guardian is now protecting your databases!');");

  // Log details
  const intervalDisplay = intervalVal;
  lines.push(`    console.log('Backup interval: ${intervalDisplay}');`);
  lines.push(`    console.log('Backup mode: ${formData.backup.mode}');`);
  lines.push(`    console.log('Databases connected: ${formData.databases.length}');`);

  lines.push('  })');
  lines.push('  .catch((err) => {');
  lines.push("    console.error('Failed to start DB Guardian:', err.message);");
  lines.push('    process.exit(1);');
  lines.push('  });');
  lines.push('');

  // Graceful shutdown
  lines.push('// ---- Graceful Shutdown ----');
  lines.push('// Cleanly stops all background tasks when your server shuts down.');
  lines.push("process.on('SIGINT', async () => {");
  lines.push("  console.log('Shutting down DB Guardian...');");
  lines.push('  await guardian.stop();');
  lines.push('  process.exit(0);');
  lines.push('});');

  return lines.join('\n');
}

/**
 * Main export: returns all generated code sections
 */
export function generateCode(formData) {
  return {
    installCmd: generateInstallCmd(),
    envExample: generateEnvExample(formData),
    setupCode: generateSetupCode(formData),
  };
}
